const fs = require("node:fs/promises");
const path = require("node:path");
const sharp = require("sharp");
const profiles = require("../public/profiles.js");
const themes = require("../public/themes.js");

const root = path.resolve(__dirname, "..");
const outputDir = path.join(root, "public/assets/previews");
const metadataPath = path.join(root, "src/profile-metadata.js");
const siteOrigin = "https://wardtap.com";

const escapeXml = (value = "") => String(value).replace(/[&<>"']/g, (character) => ({
  "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&apos;",
}[character]));

const normalize = (raw) => ({
  name: raw.display?.name || raw.fullName,
  subtitle: raw.display?.subtitle ?? raw.subtitle ?? raw.title ?? "",
  photo: raw.display?.photo ?? raw.photo ?? "",
  theme: raw.theme || "default",
  bio: raw.display?.bio ?? raw.bio ?? "",
});

const fontSizeFor = (name) => name.length > 24 ? 60 : name.length > 17 ? 70 : 82;

async function circularPhoto(photoPath) {
  const mask = Buffer.from('<svg width="230" height="230"><circle cx="115" cy="115" r="115" fill="white"/></svg>');
  return sharp(photoPath).resize(230, 230, { fit: "cover" }).composite([{ input: mask, blend: "dest-in" }]).png().toBuffer();
}

async function renderPreview(slug, profile) {
  const theme = themes[profile.theme] || themes.default;
  const photoPath = profile.photo ? path.join(root, "public", profile.photo) : "";
  let hasPhoto = false;
  try { hasPhoto = Boolean(photoPath) && (await fs.stat(photoPath)).isFile(); } catch {}
  const nameX = hasPhoto ? 390 : 90;
  const nameSize = fontSizeFor(profile.name);
  const initials = profile.name.split(/\s+/).slice(0, 2).map((part) => part[0]).join("").toUpperCase();
  const avatar = hasPhoto ? "" : `<circle cx="205" cy="315" r="115" fill="${theme.secondary}"/><text x="205" y="340" text-anchor="middle" font-size="68" font-weight="700" fill="${theme.muted}">${escapeXml(initials)}</text>`;
  const svg = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630">
    <rect width="1200" height="630" fill="${theme.page}"/>
    <rect x="54" y="54" width="1092" height="522" rx="42" fill="${theme.surface}" stroke="${theme.hairline}"/>
    ${avatar}
    <text x="90" y="125" font-family="Arial,Helvetica,sans-serif" font-size="30" font-weight="700" fill="${theme.accent}">WardTap</text>
    <text x="${nameX}" y="285" font-family="Arial,Helvetica,sans-serif" font-size="${nameSize}" font-weight="700" fill="${theme.text}">${escapeXml(profile.name)}</text>
    ${profile.subtitle ? `<text x="${nameX}" y="350" font-family="Arial,Helvetica,sans-serif" font-size="34" font-weight="500" fill="${theme.muted}">${escapeXml(profile.subtitle)}</text>` : ""}
    <text x="${nameX}" y="425" font-family="Arial,Helvetica,sans-serif" font-size="26" fill="${theme.muted}">wardtap.com/${escapeXml(slug)}</text>
  </svg>`);
  const composites = hasPhoto ? [{ input: await circularPhoto(photoPath), left: 90, top: 200 }] : [];
  await sharp(svg).composite(composites).png().toFile(path.join(outputDir, `${slug}.png`));
}

async function renderFallback() {
  const theme = themes.default;
  const svg = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630">
    <rect width="1200" height="630" fill="${theme.page}"/>
    <rect x="54" y="54" width="1092" height="522" rx="42" fill="${theme.surface}" stroke="${theme.hairline}"/>
    <text x="90" y="280" font-family="Arial,Helvetica,sans-serif" font-size="96" font-weight="700" fill="${theme.text}">WardTap</text>
    <text x="90" y="355" font-family="Arial,Helvetica,sans-serif" font-size="38" font-weight="500" fill="${theme.muted}">Digital contact cards built for a simple tap.</text>
    <text x="90" y="445" font-family="Arial,Helvetica,sans-serif" font-size="28" font-weight="700" fill="${theme.accent}">wardtap.com</text>
  </svg>`);
  await sharp(svg).png().toFile(path.join(outputDir, "wardtap.png"));
}

async function main() {
  await fs.mkdir(outputDir, { recursive: true });
  await renderFallback();
  const metadata = {};
  for (const [slug, raw] of Object.entries(profiles.profiles)) {
    const profile = normalize(raw);
    await renderPreview(slug, profile);
    metadata[slug] = {
      title: profile.name,
      documentTitle: `${profile.name} | WardTap`,
      description: profile.bio || `Tap to view ${profile.name}'s digital contact card.`,
      image: `${siteOrigin}/assets/previews/${slug}.png`,
      url: `${siteOrigin}/${slug}`,
    };
  }
  const source = `// Generated by scripts/generate-previews.js. Do not edit by hand.\nexport const FALLBACK_METADATA = ${JSON.stringify({ title: "WardTap", documentTitle: "WardTap", description: "Digital contact cards built for a simple tap.", image: `${siteOrigin}/assets/previews/wardtap.png`, url: `${siteOrigin}/` }, null, 2)};\n\nexport const PROFILE_METADATA = ${JSON.stringify(metadata, null, 2)};\n`;
  await fs.writeFile(metadataPath, source);
  console.log(`Generated ${Object.keys(metadata).length + 1} preview images and metadata for ${Object.keys(metadata).length} profiles.`);
}

main().catch((error) => { console.error(error); process.exitCode = 1; });
